// Setting keys. Private keys are stored sealed with the instance secret key.
const (
	keyConfig = "local_tls"
	keyCACert = "local_tls_ca_cert"
	keyCAKey  = "local_tls_ca_key"
	keyCert   = "local_tls_cert"
	keyKey    = "local_tls_key"

	ModeGenerate = "generate"
	ModeProvided = "provided"
)

// Store is where the settings live (the instance settings table).
type Store interface {
	Setting(ctx context.Context, key string) string
	SetSetting(ctx context.Context, key, value string) error
}

// Sealer encrypts private keys at rest (secret.Box).
type Sealer interface {
	Seal(plaintext, purpose string) (string, error)
	Open(sealed, purpose string) (string, error)
}

// Config is what the admin chooses.
type Config struct {
	Enabled bool     `json:"enabled"`
	Mode    string   `json:"mode"`  // ModeGenerate or ModeProvided
	Names   []string `json:"names"` // host names and IPs for a generated certificate
}

// Update is a save from the settings page. CertPEM and KeyPEM replace the
// provided certificate when set.
type Update struct {
	Config
	CertPEM string `json:"cert,omitempty"`
	KeyPEM  string `json:"key,omitempty"`
}

// Status is the settings page's view.
type Status struct {
	Config
	Addr      string    `json:"addr"`      // the HTTPS listen address (SLIDEKICK_HTTPS_ADDR)
	Listening bool      `json:"listening"` // HTTPS is being served now
	Error     string    `json:"error,omitempty"`
	Cert      *CertInfo `json:"cert,omitempty"`
	CA        *CertInfo `json:"ca,omitempty"` // the generated CA, when one is in use
}

// ErrInput is a problem with what the admin asked for (shown to them as is).
var ErrInput = errors.New("local HTTPS")

func inputErr(format string, a ...any) error {
	return fmt.Errorf("%w: %s", ErrInput, fmt.Sprintf(format, a...))
}

// Manager owns the HTTPS listener and its certificate.
type Manager struct {
	Store   Store
	Box     Sealer
	Addr    string       // e.g. ":7443"
	Handler http.Handler // the same handler as the HTTP listener
	Log     *slog.Logger
	Now     func() time.Time

	mu      sync.Mutex // serialises Save, Apply and the listener
	cert    atomic.Pointer[tls.Certificate]
	srv     *http.Server
	bound   string // the address actually listened on
	lastErr string
}

func (m *Manager) now() time.Time {
	if m.Now != nil {
		return m.Now()
	}
	return time.Now()
}

func (m *Manager) logger() *slog.Logger {
	if m.Log != nil {
		return m.Log
	}
	return slog.New(slog.NewTextHandler(io.Discard, nil))
}

// Config returns the saved choice (disabled and generated by default).
func (m *Manager) Config(ctx context.Context) Config {
	c := Config{Mode: ModeGenerate}
	if raw := m.Store.Setting(ctx, keyConfig); raw != "" {
		json.Unmarshal([]byte(raw), &c)
	}
	if c.Mode != ModeProvided {
		c.Mode = ModeGenerate
	}
	return c
}

func (m *Manager) secret(ctx context.Context, key string) (string, error) {
	v := m.Store.Setting(ctx, key)
	if v == "" {
		return "", nil
	}
	return m.Box.Open(v, key)
}

func (m *Manager) putSecret(ctx context.Context, key, plain string) error {
	sealed, err := m.Box.Seal(plain, key)
	if err != nil {
		return err
	}
	return m.Store.SetSetting(ctx, key, sealed)
}

// pending is a certificate change worked out but not stored yet.
type pending struct {
	caCert, caKey string // set when a new CA was made
	cert, key     string // set when a new server certificate was made or provided
}

// prepare works out the certificate for c without storing anything. pair is
// nil when there is nothing to serve (fine while HTTPS stays off).
func (m *Manager) prepare(ctx context.Context, c Config, certPEM, keyPEM string, newCA bool) (*pending, *tls.Certificate, error) {
	now := m.now()
	p := &pending{}
	if c.Mode == ModeProvided {
		if certPEM != "" || keyPEM != "" {
			pair, _, err := CheckPair(certPEM, keyPEM, now)
			if err != nil {
				return nil, nil, inputErr("%s", err.Error())
			}
			p.cert, p.key = certPEM, keyPEM
			return p, &pair, nil
		}
		cur := m.storedPair(ctx)
		if cur == nil || m.issuedByOwnCA(ctx, cur) {
			if !c.Enabled {
				return p, nil, nil
			}
			return nil, nil, inputErr("paste a certificate and its private key (PEM) to use your own certificate")
		}
		if now.After(cur.Leaf.NotAfter) {
			return nil, nil, inputErr("the provided certificate expired on %s: paste a new one", cur.Leaf.NotAfter.Format(time.RFC3339))
		}
		return p, cur, nil
	}

	// Generated: a CA of our own (made once) signs a certificate for the names.
	names, err := ParseNames(c.Names)
	if err != nil {
		if !c.Enabled && len(c.Names) == 0 {
			return p, nil, nil
		}
		return nil, nil, inputErr("%s", err.Error())
	}
	caCert := m.Store.Setting(ctx, keyCACert)
	caKey, err := m.secret(ctx, keyCAKey)
	if err != nil {
		return nil, nil, err
	}
	if newCA || caCert == "" || caKey == "" {
		if caCert, caKey, err = NewCA(names, now); err != nil {
			return nil, nil, err
		}
		p.caCert, p.caKey = caCert, caKey
	} else if cur := m.storedPair(ctx); cur != nil && fresh(cur.Leaf, caCert, names, now) {
		return p, cur, nil
	}
	cert, key, err := Issue(caCert, caKey, names, now)
	if err != nil {
		if errors.Is(err, ErrNotCovered) {
			return nil, nil, inputErr("%s", err.Error())
		}
		return nil, nil, err
	}
	pair, _, err := CheckPair(cert, key, now)
	if err != nil {
		return nil, nil, err
	}
	p.cert, p.key = cert, key
	return p, &pair, nil
}

// fresh reports whether leaf was signed by the CA, carries exactly names and
// isn't due for renewal.
func fresh(leaf *x509.Certificate, caCertPEM string, names Names, now time.Time) bool {
	if now.Add(renewBefore).After(leaf.NotAfter) || !signedBy(leaf, caCertPEM) {
		return false
	}
	want := map[string]bool{}
	for _, d := range names.DNS {
		want[d] = true
	}
	for _, ip := range names.IPs {
		want[ip.String()] = true
	}
	got := infoOf(leaf).Names
	if len(got) != len(want) {
		return false
	}
	for _, n := range got {
		if !want[n] {
			return false
		}
	}
	return true
}

func signedBy(leaf *x509.Certificate, caCertPEM string) bool {
	b, _ := pem.Decode([]byte(caCertPEM))
	if b == nil {
		return false
	}
	ca, err := x509.ParseCertificate(b.Bytes)
	return err == nil && leaf.CheckSignatureFrom(ca) == nil
}

func (m *Manager) issuedByOwnCA(ctx context.Context, cur *tls.Certificate) bool {
	ca := m.Store.Setting(ctx, keyCACert)
	return ca != "" && signedBy(cur.Leaf, ca)
}

// storedPair is the stored server certificate and key (nil if none or unreadable).
func (m *Manager) storedPair(ctx context.Context) *tls.Certificate {
	cert := m.Store.Setting(ctx, keyCert)
	key, err := m.secret(ctx, keyKey)
	if err != nil || cert == "" || key == "" {
		return nil
	}
	pair, err := tls.X509KeyPair([]byte(cert), []byte(key))
	if err != nil {
		return nil
	}
	if pair.Leaf, err = x509.ParseCertificate(pair.Certificate[0]); err != nil {
		return nil
	}
	return &pair
}

func (m *Manager) commit(ctx context.Context, c Config, p *pending) error {
	if p.caCert != "" {
		if err := m.putSecret(ctx, keyCAKey, p.caKey); err != nil {
			return err
		}
		if err := m.Store.SetSetting(ctx, keyCACert, p.caCert); err != nil {
			return err
		}
	}
	if p.cert != "" {
		if err := m.putSecret(ctx, keyKey, p.key); err != nil {
			return err
		}
		if err := m.Store.SetSetting(ctx, keyCert, p.cert); err != nil {
			return err
		}
	}
	b, _ := json.Marshal(c)
	return m.Store.SetSetting(ctx, keyConfig, string(b))
}

// Save checks and stores the admin's choice, then starts or stops HTTPS. If
// anything is wrong (a bad certificate, a name the CA can't cover, the port
// in use) nothing is stored and the error says why.
func (m *Manager) Save(ctx context.Context, u Update) (Status, error) {
	m.mu.Lock()
	defer m.mu.Unlock()
	return m.save(ctx, u, false)
}

// RotateCA replaces the generated certificate authority and the server
// certificate it signed. Devices must then trust the new CA.
func (m *Manager) RotateCA(ctx context.Context) (Status, error) {
	m.mu.Lock()
	defer m.mu.Unlock()
	c := m.Config(ctx)
	if c.Mode != ModeGenerate {
		return m.status(ctx), inputErr("the certificate authority is only used with a generated certificate")
	}
	if _, err := ParseNames(c.Names); err != nil {
		return m.status(ctx), inputErr("%s", err.Error())
	}
	return m.save(ctx, Update{Config: c}, true)
}

func (m *Manager) save(ctx context.Context, u Update, newCA bool) (Status, error) {
	c := u.Config
	if c.Mode != ModeProvided {
		c.Mode = ModeGenerate
	}
	var cleaned []string
	for _, n := range c.Names {
		if n != "" {
			cleaned = append(cleaned, n)
		}
	}
	c.Names = cleaned
	p, pair, err := m.prepare(ctx, c, u.CertPEM, u.KeyPEM, newCA)
	if err != nil {
		return m.status(ctx), err
	}
	if c.Enabled {
		if pair == nil {
			return m.status(ctx), inputErr("no certificate to serve")
		}
		if err := m.listen(pair); err != nil {
			return m.status(ctx), inputErr("can't serve HTTPS on %s: %s", m.Addr, err.Error())
		}
	} else {
		m.stop()
	}
	if err := m.commit(ctx, c, p); err != nil {
		return m.status(ctx), err
	}
	m.lastErr = ""
	return m.status(ctx), nil
}

// Apply starts or stops HTTPS to match the stored settings, renewing a
// generated certificate when it's due. Used at startup and by Run.
func (m *Manager) Apply(ctx context.Context) error {
	m.mu.Lock()
	defer m.mu.Unlock()
	c := m.Config(ctx)
	if !c.Enabled {
		m.stop()
		return nil
	}
	p, pair, err := m.prepare(ctx, c, "", "", false)
	if err == nil && pair == nil {
		err = errors.New("no certificate to serve")
	}
	if err == nil {
		err = m.commit(ctx, c, p)
	}
	if err == nil {
		err = m.listen(pair)
	}
	if err != nil {
		m.lastErr = err.Error()
		m.logger().Warn("local HTTPS is on but isn't being served", "err", err)
		return err
	}
	m.lastErr = ""
	return nil
}

// Run applies the settings now and then twice a day (renewing a generated
// certificate a month before it expires) until ctx ends, then stops HTTPS.
func (m *Manager) Run(ctx context.Context) {
	m.Apply(ctx)
	t := time.NewTicker(12 * time.Hour)
	defer t.Stop()
	for {
		select {
		case <-ctx.Done():
			m.Close()
			return
		case <-t.C:
			m.Apply(ctx)
		}
	}
}

// Close stops HTTPS.
func (m *Manager) Close() {
	m.mu.Lock()
	defer m.mu.Unlock()
	m.stop()
}

// BoundAddr is the address HTTPS is served on ("" while off).
func (m *Manager) BoundAddr() string {
	m.mu.Lock()
	defer m.mu.Unlock()
	return m.bound
}

// listen serves HTTPS with pair, starting the listener if it isn't running.
// A running listener uses the new certificate for new connections.
func (m *Manager) listen(pair *tls.Certificate) error {
	m.cert.Store(pair)
	if m.srv != nil {
		return nil
	}
	ln, err := net.Listen("tcp", m.Addr)
	if err != nil {
		return err
	}
	cfg := &tls.Config{
		MinVersion:     tls.VersionTLS12,
		GetCertificate: func(*tls.ClientHelloInfo) (*tls.Certificate, error) { return m.cert.Load(), nil },
		NextProtos:     []string{"h2", "http/1.1"},
	}
	srv := &http.Server{Handler: m.Handler, TLSConfig: cfg, ReadHeaderTimeout: 10 * time.Second, ReadTimeout: 2 * time.Minute, IdleTimeout: 2 * time.Minute,
		// Browsers that don't trust the certificate yet fail handshakes; that isn't worth a log line each.
		ErrorLog: log.New(io.Discard, "", 0)}
	m.srv, m.bound = srv, ln.Addr().String()
	m.logger().Info("serving local HTTPS", "addr", m.bound)
	go func() {
		if err := srv.ServeTLS(ln, "", ""); err != nil && !errors.Is(err, http.ErrServerClosed) {
			m.logger().Warn("local HTTPS stopped", "err", err)
		}
	}()
	return nil
}

func (m *Manager) stop() {
	if m.srv == nil {
		return
	}
	c, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	m.srv.Shutdown(c)
	m.srv, m.bound = nil, ""
	m.logger().Info("stopped local HTTPS")
}

// Status is the current state for the settings page.
func (m *Manager) Status(ctx context.Context) Status {
	m.mu.Lock()
	defer m.mu.Unlock()
	return m.status(ctx)
}

func (m *Manager) status(ctx context.Context) Status {
	st := Status{Config: m.Config(ctx), Addr: m.Addr, Listening: m.srv != nil, Error: m.lastErr}
	if st.Names == nil {
		st.Names = []string{}
	}
	if pair := m.storedPair(ctx); pair != nil {
		info := infoOf(pair.Leaf)
		st.Cert = &info
	}
	if ca := m.Store.Setting(ctx, keyCACert); ca != "" && st.Mode == ModeGenerate {
		if info, err := caInfo(ca); err == nil {
			st.CA = &info
		}
	}
	return st
}

// CACert returns the generated CA certificate (PEM) while a generated
// certificate is in use, for devices to trust.
func (m *Manager) CACert(ctx context.Context) (string, bool) {
	c := m.Config(ctx)
	ca := m.Store.Setting(ctx, keyCACert)
	if c.Mode != ModeGenerate || ca == "" {
		return "", false
	}
	return ca, true
}
