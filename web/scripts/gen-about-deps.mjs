// Lists the web libraries and fonts shipped in the build, with their versions
// and licences read from node_modules, for the about page. Runs in
// `npm run build`, so the list can't drift from what is installed.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(readFileSync(join(web, "package.json"), "utf8"));

// Runtime dependencies, plus the dev dependencies whose files end up in the
// build: the self-hosted fonts and the Tabler icon set.
const names = [
  ...Object.keys(pkg.dependencies ?? {}),
  ...Object.keys(pkg.devDependencies ?? {}).filter((n) => n.startsWith("@fontsource") || n === "@tabler/icons"),
];

const repoURL = (r) => {
  const u = typeof r === "string" ? r : r?.url;
  if (!u) return "";
  return u.replace(/^git\+/, "").replace(/\.git$/, "").replace(/^git:\/\//, "https://").replace(/^github:/, "https://github.com/");
};

const out = names
  .map((name) => {
    const p = JSON.parse(readFileSync(join(web, "node_modules", name, "package.json"), "utf8"));
    const font = name.startsWith("@fontsource");
    return {
      name: font ? `${name.replace(/^@fontsource(-variable)?\//, "")} (font)` : name,
      version: p.version,
      licence: typeof p.license === "string" ? p.license : (p.license?.type ?? "see source"),
      url: (font ? p.homepage : p.homepage || repoURL(p.repository)) || `https://www.npmjs.com/package/${name}`,
      kind: font ? "font" : "web",
    };
  })
  .sort((a, b) => a.kind.localeCompare(b.kind) || a.name.localeCompare(b.name));

writeFileSync(
  join(web, "src", "account", "about-deps.gen.ts"),
  `// Generated by scripts/gen-about-deps.mjs from package.json and node_modules. Do not edit.\nexport const WEB_DEPS = ${JSON.stringify(out, null, 1)};\n`,
);
console.log(`gen-about-deps: ${out.length} packages`);
