// Generates runtime/icons.gen.ts from the icon list in schema/catalog.json,
// taking the SVG inner markup from @tabler/icons (MIT). Fails on unknown names
// so the Go validator and the browser runtime can never disagree.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const catalog = JSON.parse(readFileSync(join(web, "..", "schema", "catalog.json"), "utf8"));
const dir = join(web, "node_modules", "@tabler", "icons", "icons", "outline");

const out = {};
const missing = [];
for (const name of catalog.icons) {
  let svg;
  try {
    svg = readFileSync(join(dir, `${name}.svg`), "utf8");
  } catch {
    missing.push(name);
    continue;
  }
  const inner = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*\/>/, "")
    .replace(/\s+/g, " ")
    .trim();
  out[name] = inner;
}
if (missing.length) {
  console.error(`gen-icons: not in @tabler/icons: ${missing.join(", ")}`);
  process.exit(1);
}
writeFileSync(
  join(web, "runtime", "icons.gen.ts"),
  `// Generated by scripts/gen-icons.mjs from schema/catalog.json. Do not edit.\n// Icons: Tabler Icons (MIT), https://tabler.io/icons\nexport const ICONS: Record<string, string> = ${JSON.stringify(out, null, 0)};\n`,
);
console.log(`gen-icons: ${Object.keys(out).length} icons`);
