// Pre-compiles schema/deck.schema.json into a standalone Ajv validator for
// the editor. Compiling at build time keeps the app's CSP free of
// 'unsafe-eval' (Ajv normally generates code at runtime).
import { readFileSync, writeFileSync } from "node:fs";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const schema = JSON.parse(readFileSync(new URL("../../schema/deck.schema.json", import.meta.url), "utf8"));
const ajv = new Ajv2020({ code: { source: true, esm: true }, allErrors: true, strict: false });
const validate = ajv.compile(schema);
// Ajv's ESM output still require()s its string-length helper; inline it so
// the module works in the browser. Any other require() is a build error.
const UCS2 = `function(str){const len=str.length;let n=0,pos=0,v;while(pos<len){n++;v=str.charCodeAt(pos++);if(v>=0xd800&&v<=0xdbff&&pos<len){v=str.charCodeAt(pos);if((v&0xfc00)===0xdc00)pos++;}}return n;}`;
let code = standaloneCode(ajv, validate).replace(/require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g, `(${UCS2})`);
if (code.includes("require(")) throw new Error("standalone validator still uses require(); inline it in gen-validator.mjs");
const js = `/* eslint-disable */\n// Generated from schema/deck.schema.json by scripts/gen-validator.mjs. Do not edit.\n${code}`;
const out = new URL("../src/editor/validate.gen.js", import.meta.url);
let prev = "";
try {
  prev = readFileSync(out, "utf8");
} catch {}
if (prev !== js) writeFileSync(out, js);
writeFileSync(
  new URL("../src/editor/validate.gen.d.ts", import.meta.url),
  `// Generated by scripts/gen-validator.mjs.\nimport type { ErrorObject } from "ajv";\ndeclare const validate: ((data: unknown) => boolean) & { errors?: ErrorObject[] | null };\nexport default validate;\n`,
);
console.log(`validate.gen.js ${prev === js ? "unchanged" : "written"} (${(js.length / 1024).toFixed(0)} KB)`);
